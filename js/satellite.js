/* =====================================================================
 * satellite.js — Satellite Monitoring section (REAL Sentinel-2 imagery).
 *
 * Places: the three research routes (KMZ centreline + 2 km study area),
 * split into ~5 km segments by python/import_routes.py. Each analysis
 * covers one segment's part of the study area.
 *
 * Two sources, same result format (python/satellite/analysis.py):
 *   Cached (offline)  data/satellite/cache_manifest.js, loaded as a plain
 *                     script, so it works when index.html is double-clicked.
 *   Live              python/satellite_server.py at CONFIG.SATELLITE_API_BASE
 *                     (downloads the scene, analyses it, adds it to the cache).
 *
 * Satellite results are observations of real roads. They are NEVER turned
 * into sand_01 / wind_01 readings and never enter the experiment log.
 * They reach the Field data panel only through applyEnvironmentData().
 * ===================================================================== */

const CUSTOM_LOCATION = "__custom";

// ---------- Research routes + offline cache (generated by python/import_routes.py
//            and python/satellite_cache.py) ----------
const SatelliteCache = {
  data: typeof SATELLITE_CACHE !== "undefined" ? SATELLITE_CACHE : { routes: [], analyses: [] },
  routes() { return this.data.routes || []; },
  route(routeId) { return this.routes().find((r) => r.id === routeId) || null; },
  segment(routeId, segmentId) {
    const r = this.route(routeId);
    return (r && r.segments.find((s) => s.id === segmentId)) || null;
  },
  analysesFor(locationId) {
    return (this.data.analyses || [])
      .filter((r) => r.location.id === locationId)
      .sort((a, b) => b.scene.date.localeCompare(a.scene.date));
  },
  find(locationId, sceneDate) {
    return this.analysesFor(locationId).find((r) => r.scene.date === sceneDate) || null;
  },
};

// ---------- Live analysis through the Python backend ----------
const SatelliteApi = {
  base() { return (CONFIG.SATELLITE_API_BASE || "").replace(/\/$/, ""); },

  async analyse(params) {
    if (!this.base()) throw new Error("Live satellite analysis is not configured (CONFIG.SATELLITE_API_BASE).");
    const query = new URLSearchParams({ ...params, mode: "live" });
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), CONFIG.SATELLITE_REQUEST_TIMEOUT_MS);
    let res;
    try {
      res = await fetch(`${this.base()}/api/satellite/analysis?${query}`, { signal: ctrl.signal });
    } catch (err) {
      throw new Error(err.name === "AbortError"
        ? "The satellite backend took too long to answer."
        : `Python satellite backend not reachable at ${this.base()}. Start it with "python python/satellite_server.py", or use Cached (offline).`);
    } finally {
      clearTimeout(timer);
    }
    const body = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error([body.error || `Backend error ${res.status}.`, body.hint].filter(Boolean).join(" "));
    return body;
  },
};

const km = (m) => (m / 1000).toFixed(1);
const segmentText = (seg, count) =>
  `Segment ${seg.index} of ${count} · km ${km(seg.start_m)}–${km(seg.end_m)} (${km(seg.length_m)} km)`;

/* ---------------------------------------------------------------------
 * One analysis -> one Field data record (schema in environmentData.js).
 * Only satellite fields are filled. Weather stays null: Sentinel-2 does
 * not measure it, and no weather service is connected.
 * For a route segment the shares describe the segment's part of the 2 km
 * study area; for a custom point the road strip (or the whole image).
 * --------------------------------------------------------------------- */
function satelliteResultToEnvironment(result) {
  const m = result.measurements;
  const seg = result.segment;
  const study = !!seg;
  const hasStrip = !study && m.sand_coverage_pct !== null && m.sand_coverage_pct !== undefined;
  const pick = (strip, area) => (hasStrip ? strip : area);
  const w = (result.location.width_m || result.location.size_m) / 1000;
  const h = (result.location.height_m || result.location.size_m) / 1000;
  return {
    timestamp: result.scene.datetime || `${result.scene.date}T00:00:00Z`,
    data_source: "sentinel-2",
    data_kind: "satellite-derived",
    scenario: null,
    location: study ? `${result.route.name}, segment ${seg.index} (km ${km(seg.start_m)}–${km(seg.end_m)})` : result.location.name,
    satellite: {
      source: "Sentinel-2 L2A",
      scene_id: result.scene.id,
      observation_date: result.scene.date,
      buffer_m: study ? result.analysis_area.study_half_width_m : (hasStrip ? m.buffer_m : null),
      coverage_basis: study
        ? `${result.analysis_area.study_half_width_m / 1000} km study area each side of the road (KMZ), ${m.area_km2} km²`
        : hasStrip
          ? `${m.buffer_m} m strip either side of the road centreline`
          : `whole ${w.toFixed(0)} × ${h.toFixed(0)} km area (no valid road geometry)`,
      sand_coverage_pct: pick(m.sand_coverage_pct, m.area_sand_coverage_pct),
      vegetation_coverage_pct: pick(m.vegetation_coverage_pct, m.area_vegetation_pct),
      bare_soil_pct: pick(m.bare_soil_pct, m.area_other_bare_pct),
      distance_to_road_m: m.distance_to_road_m,
      distance_note: m.distance_to_road_m === null ? (m.distance_to_road_m_reason || "not available") : null,
    },
    weather: { temperature_c: null, humidity_pct: null, wind_speed_mps: null },
    weather_note: "Sentinel-2 does not measure weather.",
  };
}


// ---------- The section's controls ----------
const SatelliteMonitor = {
  source: CONFIG.SATELLITE_DEFAULT_SOURCE === "live" ? "live" : "cache",
  result: null,
  onResult: null,      // set by app.js: receives the Field data record
  busy: false,

  init({ onResult }) {
    const missing = ["sat-location", "sat-segment", "sat-date-cached", "sat-date-live", "sat-source-toggle",
      "btn-sat-analyse", "sat-status", "sat-custom", "sat-buffer", "sat-selection",
      "sat-img-original", "sat-img-overlay"].filter((id) => !$(id));
    if (missing.length) throw new Error(`satellite section is missing #${missing.join(", #")}`);
    this.onResult = onResult;
    const sel = $("sat-location");
    sel.innerHTML = "";
    SatelliteCache.routes().forEach((r) => sel.add(new Option(`${r.name} (${km(r.length_m)} km)`, r.id)));
    sel.add(new Option("Custom coordinates (live only, not a research route)…", CUSTOM_LOCATION));
    $("sat-date-live").max = new Date().toISOString().slice(0, 10);
    $("sat-buffer").value = CONFIG.SATELLITE_ROAD_BUFFER_M;

    document.querySelectorAll("#sat-source-toggle button").forEach((b) =>
      b.addEventListener("click", () => this.setSource(b.dataset.source)));
    sel.addEventListener("change", () => this.routeChanged());
    $("sat-segment").addEventListener("change", () => this.segmentChanged());
    $("sat-date-cached").addEventListener("change", () => this.showCached());
    $("btn-sat-analyse").addEventListener("click", () => this.run());

    this.setSource(this.source);
  },

  route() { return SatelliteCache.route($("sat-location").value); },
  segment() {
    const r = this.route();
    return r ? SatelliteCache.segment(r.id, $("sat-segment").value) : null;
  },

  setSource(source) {
    if (this.busy) return;
    this.source = source;
    document.querySelectorAll("#sat-source-toggle button").forEach((b) =>
      b.setAttribute("aria-checked", String(b.dataset.source === source)));
    const live = source === "live";
    $("sat-date-cached").hidden = live;
    $("sat-date-live").hidden = !live;
    $("sat-buffer-group").hidden = !live;
    $("btn-sat-analyse").textContent = live ? "Analyse" : "Show";
    const customOpt = $("sat-location").querySelector(`option[value="${CUSTOM_LOCATION}"]`);
    customOpt.disabled = !live;
    if (!live && $("sat-location").value === CUSTOM_LOCATION) $("sat-location").selectedIndex = 0;
    this.routeChanged();
  },

  // Segment list for the chosen route. Cached mode: only segments with a stored analysis are enabled.
  routeChanged() {
    const custom = $("sat-location").value === CUSTOM_LOCATION;
    $("sat-custom").hidden = !custom;
    $("sat-segment-group").hidden = custom;
    const segSel = $("sat-segment");
    const previous = segSel.value;
    segSel.innerHTML = "";
    const r = this.route();
    if (r) {
      r.segments.forEach((seg) => {
        const cached = SatelliteCache.analysesFor(seg.id).length > 0;
        const opt = new Option(`${seg.index} · km ${km(seg.start_m)}–${km(seg.end_m)}${cached ? " · cached" : ""}`, seg.id);
        opt.disabled = this.source === "cache" && !cached;
        segSel.add(opt);
      });
      const keep = [...segSel.options].find((o) => o.value === previous && !o.disabled);
      const first = [...segSel.options].find((o) => !o.disabled);
      segSel.value = (keep || first || segSel.options[0]).value;
    }
    this.segmentChanged();
  },

  segmentChanged() {
    const custom = $("sat-location").value === CUSTOM_LOCATION;
    const r = this.route();
    const seg = this.segment();
    $("sat-selection").textContent = custom
      ? "Custom point: a square image around the point; road from OpenStreetMap when available. Not a research route."
      : r && seg
        ? `${r.name} · ${segmentText(seg, r.segments.length)} · analysis area: this segment's part of the ` +
          `${r.study_half_width_m / 1000} km study area each side of the road (KMZ) · image ` +
          `${km(seg.width_m)} × ${km(seg.height_m)} km around ${seg.center[1].toFixed(4)}°N, ${seg.center[0].toFixed(4)}°E`
        : "No research routes loaded (run python python/import_routes.py).";

    if (this.source === "live") {
      $("sat-date-live").value = (r && r.default_date) || $("sat-date-live").value || $("sat-date-live").max;
      this.status("idle", custom
        ? "Enter a point near a road in Saudi Arabia, pick a date and press Analyse (needs internet)."
        : "Pick a date and press Analyse. The nearest clear Sentinel-2 scene is downloaded and analysed for this segment (needs internet).");
      return;
    }
    // Cached: list the scene dates stored for this segment, newest first.
    const dates = $("sat-date-cached");
    dates.innerHTML = "";
    const cached = seg ? SatelliteCache.analysesFor(seg.id) : [];
    cached.forEach((res) => dates.add(new Option(
      `${res.scene.date} · ${res.measurements.valid_pct}% clear`, res.scene.date)));
    dates.disabled = cached.length === 0;
    if (cached.length) {
      this.showCached();
    } else {
      this.clear();
      this.status("error", "No cached images for this route yet. Switch to Live, or run python python/satellite_cache.py --route N --segments ….");
    }
  },

  showCached() {
    const seg = this.segment();
    const r = seg && SatelliteCache.find(seg.id, $("sat-date-cached").value);
    if (!r) return;
    this.render(r, "");
    this.status("ok", `Cached analysis (works offline) · scene ${r.scene.id}, acquired ${r.scene.date}.`);
  },

  async run() {
    if (this.source === "cache") return this.showCached();
    if (this.busy) return;
    const date = $("sat-date-live").value;
    if (!date) return this.status("error", "Choose an observation date.");
    let params;
    if ($("sat-location").value === CUSTOM_LOCATION) {
      const lat = parseFloat($("sat-lat").value);
      const lon = parseFloat($("sat-lon").value);
      if (!Number.isFinite(lat) || !Number.isFinite(lon)) return this.status("error", "Enter latitude and longitude in decimal degrees.");
      params = { lat, lon, date };
    } else {
      const seg = this.segment();
      if (!seg) return this.status("error", "Choose a route segment.");
      params = { segment: seg.id, date };
    }
    const buffer = parseInt($("sat-buffer").value, 10);
    if (!Number.isFinite(buffer) || buffer < 10 || buffer > 2000) {
      return this.status("error", "Road buffer must be 10–2000 m (inside the 2 km study area).");
    }
    params.buffer_m = buffer;

    this.setBusy(true);
    this.status("loading", "Finding the nearest clear Sentinel-2 scene, downloading the bands and detecting sand… (about 10–60 s)");
    try {
      const r = await SatelliteApi.analyse(params);
      this.render(r, SatelliteApi.base());
      const shifted = r.scene.date !== r.requested_date ? ` (nearest clear scene to ${r.requested_date})` : "";
      this.status("ok", `Live analysis · scene ${r.scene.id}, acquired ${r.scene.date}${shifted}. Saved to the local cache.`);
    } catch (err) {
      this.status("error", err.message);
    } finally {
      this.setBusy(false);
    }
  },

  setBusy(busy) {
    this.busy = busy;
    $("btn-sat-analyse").disabled = busy;
    $("btn-sat-analyse").textContent = busy ? "Analysing…" : (this.source === "live" ? "Analyse" : "Show");
  },

  status(state, text) {
    $("sat-status").dataset.state = state;
    $("sat-status").textContent = text;
  },

  clear() {
    this.result = null;
    ["sat-img-original", "sat-img-overlay"].forEach((id) => $(id).removeAttribute("src"));
    ["s-strip", "s-dist", "s-area", "s-route", "s-segment", "s-scene", "s-extent", "s-valid", "s-road",
      "s-provider", "s-processed"].forEach((id) => { $(id).textContent = "—"; });
    $("s-strip-label").textContent = "Sand in road buffer";
    $("btn-sat-use").disabled = true;
  },

  render(r, imageBase) {
    this.result = r;
    const url = (p) => (imageBase ? `${imageBase}/${p}` : p);
    $("sat-img-original").src = url(r.images.original);
    $("sat-img-overlay").src = url(r.images.overlay);

    const m = r.measurements;
    const seg = r.segment;
    const show = (v) => (v === null || v === undefined ? "—" : v);
    $("s-area").textContent = show(m.area_sand_coverage_pct);
    $("s-area-label").textContent = seg ? `Sand, ${r.analysis_area.study_half_width_m / 1000} km study area` : "Sand, whole image";
    $("s-strip").textContent = show(m.sand_coverage_pct);
    $("s-strip-label").textContent = m.buffer_m ? `Sand within ${m.buffer_m} m of road` : "Sand in road buffer";
    $("s-dist").textContent = show(m.distance_to_road_m);

    $("s-route").textContent = seg ? `${r.route.name} · ${km(r.route.length_m)} km` : "Custom point (not a research route)";
    $("s-segment").textContent = seg ? segmentText(seg, seg.count) : "—";
    $("s-scene").textContent = `${r.scene.date} · ${r.scene.id}` +
      (r.scene.tile_cloud_pct !== null ? ` · tile cloud ${r.scene.tile_cloud_pct}%` : "") +
      (r.scene.date !== r.requested_date ? ` · requested ${r.requested_date}` : "");
    const w = (r.location.width_m || r.location.size_m) / 1000;
    const h = (r.location.height_m || r.location.size_m) / 1000;
    const [W, S, E, N] = r.location.bounds_wgs84;
    $("s-extent").textContent = seg
      ? `${m.area_km2} km² (segment part of the ${r.analysis_area.study_half_width_m / 1000} km study area) · ` +
        `image ${w.toFixed(1)} × ${h.toFixed(1)} km around ${r.location.lat.toFixed(4)}°N, ${r.location.lon.toFixed(4)}°E`
      : `${w.toFixed(1)} × ${h.toFixed(1)} km around ${r.location.lat.toFixed(4)}°N, ${r.location.lon.toFixed(4)}°E`;
    $("s-extent").title = `W ${W}, S ${S}, E ${E}, N ${N} (EPSG:${r.location.epsg} for the analysis)`;
    $("s-valid").textContent = `${m.valid_pct}% (cloud ${m.cloud_pct}%)`;
    $("s-road").textContent = r.road.available
      ? r.road.source
      : `None: ${r.road.reason}. Distance and road buffer not computed.`;
    $("s-provider").textContent = r.scene.provider;
    $("s-processed").textContent = `${r.processing.processed_at.replace("T", " ").replace("Z", " UTC")} · method v${r.processing.version}`;
    $("btn-sat-use").disabled = false;

    if (this.onResult) this.onResult(satelliteResultToEnvironment(r));
  },
};
