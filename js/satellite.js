/* =====================================================================
 * satellite.js — Satellite Monitoring section (REAL Sentinel-2 imagery).
 *
 * Two sources, same result format (python/satellite/analysis.py):
 *   Cached (offline)  data/satellite/cache_manifest.js, loaded as a plain
 *                     script, so it works when index.html is double-clicked.
 *   Live              python/satellite_server.py at CONFIG.SATELLITE_API_BASE
 *                     (downloads the scene, analyses it, adds it to the cache).
 *
 * Satellite results are observations of real roads. They are NEVER turned
 * into sand_01 / wind_01 readings and never enter the experiment log.
 * They reach the Field data panel only through applyEnvironmentData().
 * ===================================================================== */

const CUSTOM_LOCATION = "__custom";

// ---------- Offline cache (generated by python/satellite_cache.py) ----------
const SatelliteCache = {
  data: typeof SATELLITE_CACHE !== "undefined" ? SATELLITE_CACHE : { locations: [], analyses: [] },
  // Configured locations, plus custom points that were analysed live earlier.
  locations() {
    const list = [...(this.data.locations || [])];
    (this.data.analyses || []).forEach((r) => {
      if (!list.some((l) => l.id === r.location.id)) list.push({ ...r.location, default_date: r.requested_date });
    });
    return list;
  },
  analysesFor(locationId) {
    return (this.data.analyses || [])
      .filter((r) => r.location.id === locationId)
      .sort((a, b) => b.scene.date.localeCompare(a.scene.date));
  },
  find(locationId, sceneDate) {
    return this.analysesFor(locationId).find((r) => r.scene.date === sceneDate) || null;
  },
};

// ---------- Live analysis through the Python backend ----------
const SatelliteApi = {
  base() { return (CONFIG.SATELLITE_API_BASE || "").replace(/\/$/, ""); },

  async analyse(params) {
    if (!this.base()) throw new Error("Live satellite analysis is not configured (CONFIG.SATELLITE_API_BASE).");
    const query = new URLSearchParams({ ...params, mode: "live" });
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), CONFIG.SATELLITE_REQUEST_TIMEOUT_MS);
    let res;
    try {
      res = await fetch(`${this.base()}/api/satellite/analysis?${query}`, { signal: ctrl.signal });
    } catch (err) {
      throw new Error(err.name === "AbortError"
        ? "The satellite backend took too long to answer."
        : `Python satellite backend not reachable at ${this.base()}. Start it with "python python/satellite_server.py", or use Cached (offline).`);
    } finally {
      clearTimeout(timer);
    }
    const body = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error([body.error || `Backend error ${res.status}.`, body.hint].filter(Boolean).join(" "));
    return body;
  },
};

/* ---------------------------------------------------------------------
 * One analysis -> one Field data record (schema in environmentData.js).
 * Only satellite fields are filled. Weather stays null: Sentinel-2 does
 * not measure it, and no weather service is connected.
 * --------------------------------------------------------------------- */
function satelliteResultToEnvironment(result) {
  const m = result.measurements;
  const hasStrip = m.sand_coverage_pct !== null && m.sand_coverage_pct !== undefined;
  const km = (result.location.size_m / 1000).toFixed(0);
  return {
    timestamp: result.scene.datetime || `${result.scene.date}T00:00:00Z`,
    data_source: "sentinel-2",
    data_kind: "satellite-derived",
    scenario: null,
    location: result.location.name,
    satellite: {
      source: "Sentinel-2 L2A",
      scene_id: result.scene.id,
      observation_date: result.scene.date,
      buffer_m: hasStrip ? m.buffer_m : null,
      coverage_basis: hasStrip
        ? `${m.buffer_m} m strip either side of the road centreline`
        : `whole ${km} × ${km} km area (no valid road geometry)`,
      sand_coverage_pct: hasStrip ? m.sand_coverage_pct : m.area_sand_coverage_pct,
      vegetation_coverage_pct: hasStrip ? m.vegetation_coverage_pct : m.area_vegetation_pct,
      bare_soil_pct: hasStrip ? m.bare_soil_pct : m.area_other_bare_pct,
      distance_to_road_m: m.distance_to_road_m,
      distance_note: m.distance_to_road_m === null ? (m.distance_to_road_m_reason || "not available") : null,
    },
    weather: { temperature_c: null, humidity_pct: null, wind_speed_mps: null },
    weather_note: "Sentinel-2 does not measure weather and no weather source is connected.",
  };
}


// ---------- The section's controls ----------
const SatelliteMonitor = {
  source: CONFIG.SATELLITE_DEFAULT_SOURCE === "live" ? "live" : "cache",
  result: null,
  onResult: null,      // set by app.js: receives the Field data record
  busy: false,

  init({ onResult }) {
    const missing = ["sat-location", "sat-date-cached", "sat-date-live", "sat-source-toggle", "btn-sat-analyse",
      "sat-status", "sat-custom", "sat-img-original", "sat-img-overlay"].filter((id) => !$(id));
    if (missing.length) throw new Error(`satellite section is missing #${missing.join(", #")}`);
    this.onResult = onResult;
    const sel = $("sat-location");
    sel.innerHTML = "";
    SatelliteCache.locations().forEach((loc) => sel.add(new Option(loc.name, loc.id)));
    sel.add(new Option("Custom coordinates (live only)…", CUSTOM_LOCATION));
    $("sat-date-live").max = new Date().toISOString().slice(0, 10);

    document.querySelectorAll("#sat-source-toggle button").forEach((b) =>
      b.addEventListener("click", () => this.setSource(b.dataset.source)));
    sel.addEventListener("change", () => this.locationChanged());
    $("sat-date-cached").addEventListener("change", () => this.showCached());
    $("btn-sat-analyse").addEventListener("click", () => this.run());

    this.setSource(this.source);
  },

  location() {
    return SatelliteCache.locations().find((l) => l.id === $("sat-location").value) || null;
  },

  setSource(source) {
    if (this.busy) return;
    this.source = source;
    document.querySelectorAll("#sat-source-toggle button").forEach((b) =>
      b.setAttribute("aria-checked", String(b.dataset.source === source)));
    const live = source === "live";
    $("sat-date-cached").hidden = live;
    $("sat-date-live").hidden = !live;
    $("btn-sat-analyse").textContent = live ? "Analyse" : "Show";
    const customOpt = $("sat-location").querySelector(`option[value="${CUSTOM_LOCATION}"]`);
    customOpt.disabled = !live;
    if (!live && $("sat-location").value === CUSTOM_LOCATION) $("sat-location").selectedIndex = 0;
    this.locationChanged();
  },

  locationChanged() {
    const custom = $("sat-location").value === CUSTOM_LOCATION;
    $("sat-custom").hidden = !custom;
    const loc = this.location();
    if (this.source === "live") {
      $("sat-date-live").value = (loc && loc.default_date) || $("sat-date-live").value || $("sat-date-live").max;
      this.status("idle", custom
        ? "Enter a point near a road in Saudi Arabia, pick a date and press Analyse (needs internet)."
        : "Pick a date and press Analyse. The nearest clear Sentinel-2 scene is downloaded and analysed (needs internet).");
      return;
    }
    // Cached: list the scene dates stored for this location, newest first.
    const dates = $("sat-date-cached");
    dates.innerHTML = "";
    const cached = loc ? SatelliteCache.analysesFor(loc.id) : [];
    cached.forEach((r) => dates.add(new Option(
      `${r.scene.date} · ${r.measurements.valid_pct}% clear`, r.scene.date)));
    dates.disabled = cached.length === 0;
    if (cached.length) {
      this.showCached();
    } else {
      this.clear();
      this.status("error", "No cached images for this location. Switch to Live, or run python python/satellite_cache.py.");
    }
  },

  showCached() {
    const loc = this.location();
    const r = loc && SatelliteCache.find(loc.id, $("sat-date-cached").value);
    if (!r) return;
    this.render(r, "");
    this.status("ok", `Cached analysis (works offline) · scene ${r.scene.id}, acquired ${r.scene.date}.`);
  },

  async run() {
    if (this.source === "cache") return this.showCached();
    if (this.busy) return;
    const date = $("sat-date-live").value;
    if (!date) return this.status("error", "Choose an observation date.");
    let params;
    if ($("sat-location").value === CUSTOM_LOCATION) {
      const lat = parseFloat($("sat-lat").value);
      const lon = parseFloat($("sat-lon").value);
      if (!Number.isFinite(lat) || !Number.isFinite(lon)) return this.status("error", "Enter latitude and longitude in decimal degrees.");
      params = { lat, lon, date };
    } else {
      params = { location: $("sat-location").value, date };
    }

    this.setBusy(true);
    this.status("loading", "Finding the nearest clear Sentinel-2 scene, downloading the bands and detecting sand… (about 10–60 s)");
    try {
      const r = await SatelliteApi.analyse(params);
      this.render(r, SatelliteApi.base());
      const shifted = r.scene.date !== r.requested_date ? ` (nearest clear scene to ${r.requested_date})` : "";
      this.status("ok", `Live analysis · scene ${r.scene.id}, acquired ${r.scene.date}${shifted}. Saved to the local cache.`);
    } catch (err) {
      this.status("error", err.message);
    } finally {
      this.setBusy(false);
    }
  },

  setBusy(busy) {
    this.busy = busy;
    $("btn-sat-analyse").disabled = busy;
    $("btn-sat-analyse").textContent = busy ? "Analysing…" : (this.source === "live" ? "Analyse" : "Show");
  },

  status(state, text) {
    $("sat-status").dataset.state = state;
    $("sat-status").textContent = text;
  },

  clear() {
    this.result = null;
    ["sat-img-original", "sat-img-overlay"].forEach((id) => $(id).removeAttribute("src"));
    ["s-strip", "s-dist", "s-area", "s-scene", "s-extent", "s-valid", "s-road", "s-provider", "s-processed"]
      .forEach((id) => { $(id).textContent = "—"; });
    $("btn-sat-use").disabled = true;
  },

  render(r, imageBase) {
    this.result = r;
    const url = (p) => (imageBase ? `${imageBase}/${p}` : p);
    $("sat-img-original").src = url(r.images.original);
    $("sat-img-overlay").src = url(r.images.overlay);

    const m = r.measurements;
    const show = (v) => (v === null || v === undefined ? "—" : v);
    $("s-strip").textContent = show(m.sand_coverage_pct);
    $("s-dist").textContent = show(m.distance_to_road_m);
    $("s-area").textContent = show(m.area_sand_coverage_pct);
    $("s-scene").textContent = `${r.scene.id} · ${r.scene.date}` +
      (r.scene.tile_cloud_pct !== null ? ` · tile cloud ${r.scene.tile_cloud_pct}%` : "");
    const [w, s, e, n] = r.location.bounds_wgs84;
    $("s-extent").textContent = `${r.location.size_m / 1000} × ${r.location.size_m / 1000} km around ` +
      `${r.location.lat.toFixed(4)}°N, ${r.location.lon.toFixed(4)}°E`;
    $("s-extent").title = `W ${w}, S ${s}, E ${e}, N ${n}`;
    $("s-valid").textContent = `${m.valid_pct}% (cloud ${m.cloud_pct}%)`;
    $("s-road").textContent = r.road.available
      ? r.road.source
      : `None: ${r.road.reason}. Distance and road strip not computed.`;
    $("s-provider").textContent = r.scene.provider;
    $("s-processed").textContent = `${r.processing.processed_at.replace("T", " ").replace("Z", " UTC")} · method v${r.processing.version}`;
    $("btn-sat-use").disabled = false;

    if (this.onResult) this.onResult(satelliteResultToEnvironment(r));
  },
};
