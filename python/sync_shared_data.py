"""
sync_shared_data.py — keeps js/sharedMockData.js identical to data/shared_mock_data.json.

Why: browsers block reading a .json file when index.html is opened by
double-click (file://). The dashboard therefore tries data/shared_mock_data.json
first and falls back to this embedded copy. The copy must never drift.

    python python/sync_shared_data.py          # rewrite the JS copy from the JSON
    python python/sync_shared_data.py --check  # exit 1 if they differ

Never edit js/sharedMockData.js by hand. Edit nothing in shared_mock_data.json
either unless the team agrees a new version (see data/SHARED_MOCK_DATA_README.txt).
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "data" / "shared_mock_data.json"
JS_PATH = ROOT / "js" / "sharedMockData.js"

HEADER = (
    "/* GENERATED by python/sync_shared_data.py from data/shared_mock_data.json.\n"
    " * Do not edit by hand. Used only when the browser cannot read the JSON file\n"
    " * (index.html opened by double-click). Content is the unchanged JSON text. */\n"
    "const SHARED_MOCK_DATA_EMBEDDED = "
)
FOOTER = ";\n"


def expected_js() -> str:
    return HEADER + JSON_PATH.read_text(encoding="utf-8").rstrip("\n") + FOOTER


if __name__ == "__main__":
    want = expected_js()
    if "--check" in sys.argv:
        have = JS_PATH.read_text(encoding="utf-8") if JS_PATH.exists() else ""
        if have != want:
            sys.exit("js/sharedMockData.js is OUT OF SYNC with data/shared_mock_data.json. Run without --check.")
        print("OK: embedded copy matches data/shared_mock_data.json")
    else:
        JS_PATH.write_text(want, encoding="utf-8")
        print(f"Wrote {JS_PATH.relative_to(ROOT)}")
