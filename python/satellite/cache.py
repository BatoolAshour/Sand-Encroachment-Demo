"""
cache.py — the offline cache and the manifest the dashboard reads.

The dashboard must work by double-clicking index.html (no server), and a
browser cannot list folders or read JSON from file:// pages. So after every
analysis the cache is summarised into data/satellite/cache_manifest.js:

    const SATELLITE_CACHE = { generated_at, locations: [...], analyses: [...] };

Images are referenced by relative path and load fine from file://.
"""

from __future__ import annotations

import datetime as dt
import json

from .analysis import CACHE_DIR, SAT_DIR, load_locations

MANIFEST_JS = SAT_DIR / "cache_manifest.js"


def cached_results():
    results = []
    for path in sorted(CACHE_DIR.glob("*/*/result.json")):
        try:
            results.append(json.loads(path.read_text(encoding="utf-8")))
        except (OSError, ValueError):
            continue
    return results


def find_cached(location_id, scene_date=None):
    """Cached result for a location: exact scene date, or the newest one."""
    matches = [r for r in cached_results() if r["location"]["id"] == location_id]
    if scene_date:
        matches = [r for r in matches if r["scene"]["date"] == scene_date]
    return max(matches, key=lambda r: r["scene"]["date"]) if matches else None


def write_manifest():
    manifest = {
        "generated_at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "locations": load_locations(),
        "analyses": cached_results(),
    }
    text = ("/* GENERATED by python/satellite_cache.py (or the satellite server) from\n"
            " * data/satellite/cache/<location>/<date>/result.json. Do not edit by hand.\n"
            " * Real Sentinel-2 analyses for offline use; see README section 10. */\n"
            "const SATELLITE_CACHE = " + json.dumps(manifest, indent=1) + ";\n")
    MANIFEST_JS.write_text(text, encoding="utf-8")
    return manifest
